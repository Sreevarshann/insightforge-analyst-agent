def _html_table(t: dict[str, Any]) -> str:
    e = html.escape
    head = "".join(f"<th>{e(str(c))}</th>" for c in t["columns"])
    body = "".join(
        "<tr>"
        + "".join(
            f'<td class="{"n" if isinstance(v, (int, float)) else ""}">{e("" if v is None else str(v))}</td>'
            for v in r
        )
        + "</tr>"
        for r in t["rows"][:MAX_TABLE_ROWS]
    )
    more = (
        f"<p class=meta>{len(t['rows']) - MAX_TABLE_ROWS} more rows omitted.</p>"
        if len(t["rows"]) > MAX_TABLE_ROWS
        else ""
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>{more}"


def to_html(a: Analysis) -> str:
    e = html.escape
    v = a.verification_json or {}
    status = v.get("status", "n/a")
    parts = [
        f"<h1>{e(a.title or 'Analysis')}</h1>",
        f"<p class=meta>{e(a.question)}</p>",
        f"<p class=meta>{e(a.created_at.isoformat())} · {e(a.model_name or '')} · <span class='badge{'' if status == 'verified' else ' warn'}'>{e(status)}</span></p>",
        f"<h2>Answer</h2><div class=answer>{e(a.explanation or '')}</div>",
    ]
    for i, c in enumerate(a.charts_json):
        fig = go.Figure(c["figure"])
        parts.append(
            "<div class=card>"
            + pio.to_html(
                fig,
                include_plotlyjs="cdn" if i == 0 else False,
                full_html=False,
                config={"displaylogo": False},
            )
            + "</div>"
        )
    for s in a.steps_json:
        parts.append(f"<h2>Step {s['step']}: {e(s.get('purpose') or s['op'])}</h2>")
        parts.append(f"<pre>{e(json.dumps(s['args'], indent=2, default=str))}</pre>")
        parts += [f"<pre>{e(sql)}</pre>" for sql in s.get("sql", [])]
        parts += [_html_table(t) for t in s["tables"] if t["name"] != "raw"]
        parts += [f"<p class=meta>{e(n)}</p>" for n in s.get("notes", [])]
    if v.get("removed_sentences"):
        parts.append(
            "<h2>Verification</h2><ul>"
            + "".join(
                f"<li><del>{e(r['sentence'])}</del> — {e(r['reason'])}</li>"
                for r in v["removed_sentences"]
            )
            + "</ul>"
        )
    parts.append(
        f"<p class=meta>Generated by InsightForge {e(__version__)}. Dataset versions: {e(', '.join(a.dataset_versions))}</p>"
    )
    return f"<!doctype html><html lang=en><head><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'><title>{e(a.title or 'Analysis')}</title><style>{CSS}</style></head><body><main>{''.join(parts)}</main></body></html>"


def table_csv(table: dict[str, Any]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(table["columns"])
    for r in table["rows"]:
        # neutralise spreadsheet formula injection
        w.writerow(["'" + v if isinstance(v, str) and v[:1] in "=+-@\t\r" else v for v in r])
    return buf.getvalue()
